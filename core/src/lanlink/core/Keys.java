package lanlink.core;

/** Key codes carried by KEY messages. They match java.awt.event.KeyEvent VK_ values. */
public final class Keys {
    private Keys() {}

    public static final int BACK_SPACE = 8, TAB = 9, ENTER = 10;
    public static final int SHIFT = 16, CONTROL = 17, ALT = 18, ESCAPE = 27;
    public static final int PAGE_UP = 33, PAGE_DOWN = 34, END = 35, HOME = 36;
    public static final int LEFT = 37, UP = 38, RIGHT = 39, DOWN = 40;
    public static final int ZERO = 48, A = 65, F1 = 112, DELETE = 127, PRINT_SCREEN = 154, WINDOWS = 524;
}
